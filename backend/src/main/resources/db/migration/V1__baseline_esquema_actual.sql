-- Índice GiST parcial para la búsqueda espacial (RNF-03): solo sobre
-- técnicos activos, aprobados y disponibles — el mismo predicado que
-- siempre aplica PostgisTecnicoDisponibilidadAdapter.
CREATE INDEX idx_tecnico_disponible_ubicacion_geo
    ON tecnico USING GIST ((ST_MakePoint(longitud, latitud)::geography))
    WHERE activo = true AND estado_validacion = 'APROBADO' AND estado_operativo = 'DISPONIBLE';
